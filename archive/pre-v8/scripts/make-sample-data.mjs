// Generates SAMPLE data in the same shape the real build script will produce,
// so the page can be built before real VD data exists.
// Output: web/data/neihu-data.js  (sets window.NEIHU_DATA)
//
// Every number here is invented. The page shows a "樣本資料" banner while
// meta.source === 'sample'.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// 15-minute slots, 06:45 .. 10:15 (slot start times). Model horizon covers
// shifts of up to 60 minutes past the 09:30 end of the peak window.
const SLOT_MIN = 15;
const FIRST = 6 * 60 + 45;
const N = 15;
const slots = Array.from({ length: N }, (_, i) => {
  const m = FIRST + i * SLOT_MIN;
  return `${String(Math.floor(m / 60)).padStart(2, '0')}:${String(m % 60).padStart(2, '0')}`;
});

